function setLanguage(lang) {
    if (!translations[lang]) return;

    // 1. Update Text Content
    const elements = document.querySelectorAll('[data-i18n]');
    elements.forEach(el => {
        const key = el.getAttribute('data-i18n');
        const keys = key.split('.');
        let text = translations[lang];
        keys.forEach(k => {
            if (text) text = text[k];
        });
        if (text) {
            if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
                el.placeholder = text;
            } else {
                el.innerHTML = text; // Use innerHTML to allow simple HTML like <br>
            }
        }
    });

    // 2. Update Meta Tags (Dynamic SEO)
    const metaData = translations[lang].meta;
    if (metaData) {
        document.title = metaData.title;

        let descMeta = document.querySelector('meta[name="description"]');
        if (!descMeta) {
            descMeta = document.createElement('meta');
            descMeta.name = 'description';
            document.head.appendChild(descMeta);
        }
        descMeta.content = metaData.description;

        let kwMeta = document.querySelector('meta[name="keywords"]');
        if (!kwMeta) {
            kwMeta = document.createElement('meta');
            kwMeta.name = 'keywords';
            document.head.appendChild(kwMeta);
        }
        kwMeta.content = metaData.keywords;
    }

    // 3. Update HTML Lang Attribute
    document.documentElement.lang = lang;

    // 4. Save Preference
    localStorage.setItem('preferredLanguage', lang);

    // 5. Update Active Flag State (Visual Feedback)
    // 5. Update Active Flag State (Visual Feedback)
    document.querySelectorAll('.lang-btn').forEach(btn => {
        // Only manage active state if the button has data-lang (dynamic mode)
        if (btn.hasAttribute('data-lang')) {
            btn.classList.remove('active');
            if (btn.dataset.lang === lang) {
                btn.classList.add('active');
            }
        }
    });

    console.log(`Language set to ${lang}`);
}

// Initialize Language on Load
document.addEventListener('DOMContentLoaded', () => {
    // Priority: 1. HTML lang attribute (static pages), 2. Saved Preference, 3. Default 'fr'
    const htmlLang = document.documentElement.lang;
    const savedLang = localStorage.getItem('preferredLanguage');
    const supportedLangs = Object.keys(translations);

    let targetLang = 'fr';

    if (htmlLang && supportedLangs.includes(htmlLang)) {
        targetLang = htmlLang;
    } else if (savedLang && supportedLangs.includes(savedLang)) {
        targetLang = savedLang;
    }

    setLanguage(targetLang);
});

